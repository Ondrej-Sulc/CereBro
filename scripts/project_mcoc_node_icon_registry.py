"""Project tiny presentation choices and exact version bindings from reviewed art.

No database, game or network access. Does not modify extraction/source artifacts.
"""
import json
from pathlib import Path
from extract_mcoc_node_modifiers import digest_json

LABELS = {
    'a': 'Armor', 'b': 'Bleed', '-': 'Dice', 'k': 'Attack / Fury',
    'v': 'Energy / Power rate', 'u': 'Physical resistance', 'm': 'Power drain',
    'S': 'Special attack', 'Z': 'Heal block', 'H': 'Health', '\u00a2': 'Attack and Health',
    '>': 'Parry / Stun immunity', 'x': 'Recovery', '\ue414': 'Stymied',
    '\u00d4': 'Critical stats', 'K': 'Timer', '\u2122': 'Spade', 'D': 'Critical damage',
    '\u00a5': 'Lunatic', '\ue848': 'Power lock', '\u02c6': 'Skill', '<': 'Stun',
    'N': 'Power gain', '\ue966': 'Aspect of Strength',
}


def project(root):
    art = json.loads((root/'src/data/game-node-modifiers/artwork.json').read_text(encoding='utf-8'))
    if art['contentHash'] != digest_json({key: value for key, value in art.items() if key != 'contentHash'}):
        raise ValueError('Artwork hash mismatch; re-extract/review before publishing icon choices')
    icons, bindings = {}, []
    for row in art['icons']:
        if row['status'] != 'verified':
            continue
        key = 'node-glyph-'+row['sha256'][:16]
        item = dict(key=key, label=LABELS[row['glyph']], src=row['src'])
        if key in icons and icons[key] != item:
            raise ValueError('Icon key collision')
        icons[key] = item
        bindings.append(dict(effectId=row['effectId'], versionHash=row['versionHash'], iconKey=key))
    source = '// Generated by scripts/project_mcoc_node_icon_registry.py; native shapes are immutable.\n'
    source += 'export const nativeModifierIcons = '+json.dumps(sorted(icons.values(), key=lambda x: x['label']), indent=2)+' as const\n'
    (root/'src/domain/node-modifiers/native-icon-registry.ts').write_text(source, encoding='utf-8')
    result = dict(contract='cerebro.node-modifier-icon-bindings/v1', artworkHash=art['contentHash'],
                  modifierCatalogHash=art['modifierCatalogHash'], bindings=bindings)
    (root/'src/data/game-node-modifiers/icon-bindings.json').write_text(json.dumps(result, indent=2)+'\n', encoding='utf-8')
    print(f'{len(icons)} presentation choices; {len(bindings)} exact version bindings')


if __name__ == '__main__':
    project(Path(__file__).resolve().parents[1])
